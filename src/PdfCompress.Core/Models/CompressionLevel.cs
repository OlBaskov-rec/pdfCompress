namespace PdfCompress.Core.Models;

/// <summary>
/// Пять фиксированных степеней сжатия — то, что видит пользователь в переключателе.
/// Числовые значения (1..5) стабильны: они сохраняются в настройках.
/// </summary>
public enum CompressionLevel
{
    /// <summary>Минимальное: качество почти без потерь, экономия за счёт перепаковки потоков.</summary>
    Minimal = 1,

    /// <summary>Слабое: печатное качество (220 dpi).</summary>
    Light = 2,

    /// <summary>Среднее: универсальный вариант для документооборота (150 dpi).</summary>
    Medium = 3,

    /// <summary>Сильное: чтение с экрана (110 dpi).</summary>
    Strong = 4,

    /// <summary>Максимальное: минимальный размер, качество «для просмотра» (72 dpi).</summary>
    Maximum = 5,
}
